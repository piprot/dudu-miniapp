// 按当前小时返回时段 key：'早'|'午'|'晚'|'深夜'
function timeSlotOf(date) {
  const h = (date ? new Date(date) : new Date()).getHours();
  if (h >= 5 && h < 11) return '早';
  if (h >= 11 && h < 17) return '午';
  if (h >= 17 && h < 23) return '晚';
  return '深夜';
}

// 今日主文案：时段 > 季节 > 通用（三层兜底，永不返回空）
function pickDailyLine(date) {
  const slot = timeSlotOf(date);
  const season = seasonOf(date);
  const pool = TIME_LINES[slot] || SEASON_LINES[season] || DAILY_LINES;
  const text = pickDaily(pool, date, 'daily:' + slot + ':' + season);
  return {
    slot,
    season,
    text: text || DAILY_LINES[dayIndex(date) % DAILY_LINES.length]
  };
}

// 指定要「季节感优先」（给节气模块用）
function pickSeasonLine(date) {
  const season = seasonOf(date);
  const pool = SEASON_LINES[season] || DAILY_LINES;
  return pickDaily(pool, date, 'season:' + season);
}

// 取今日 n 条不重复的通用文案（给「换一批」用）
function pickDailyBatch(date, n) {
  return pickDailyMulti(DAILY_LINES, date, 'batch', n).map(t => ({ text: t }));
}

function stats() {
  return {
    daily: DAILY_LINES.length,
    seasons: Object.keys(SEASON_LINES).map(k => k + ':' + SEASON_LINES[k].length).join(' '),
    times: Object.keys(TIME_LINES).map(k => k + ':' + TIME_LINES[k].length).join(' '),
    total: DAILY_LINES.length
      + Object.keys(SEASON_LINES).reduce((a, k) => a + SEASON_LINES[k].length, 0)
      + Object.keys(TIME_LINES).reduce((a, k) => a + TIME_LINES[k].length, 0)
  };
}

