// 取某类型某天的种子文案（offset 用于「换一套」，与金句库同一套确定性轮换逻辑）
function seedForType(type, dateStr, offset) {
  const pool = TYPE_POOLS[type];
  if (!pool || !pool.length) return null;
  const N = pool.length;
  const di = dayIndexOf(dateStr);
  const k = Math.max(0, Number(offset) || 0);
  const idx = ((di + k * STEP) % N + N) % N;
  const raw = pool[idx];
  if (!raw) return null;
  const out = {};
  if (raw.t !== undefined) out.title = raw.t;
  if (raw.b !== undefined) out.body = raw.b;
  if (raw.g !== undefined) out.tag = raw.g;
  if (raw.items !== undefined) out.items = raw.items.slice();
  return out;
}

// 某类型文案池储备量（dailysign / quote 返回通用金句库容量；未知类型返回 null）
function poolSizeFor(type) {
  if (type === 'dailysign' || type === 'quote') return FLAT.length;
  const pool = TYPE_POOLS[type];
  return pool ? pool.length : null;
}

// ── 内部工具 ──
const CAT_NAME = { morning: '早安', night: '晚安', growth: '成长', life: '生活', craft: '创作', mood: '心绪' };

// 展平为 [{t, c}]，并保证总条数与步长 97 互质（不是 97 的倍数），否则补一条兜底句。
let FLAT = [];
(function build() {
  for (const g of Object.keys(POOL)) {
    for (const t of POOL[g]) FLAT.push({ t: String(t || '').trim(), c: CAT_NAME[g] || '' });
  }
  FLAT = FLAT.filter(x => x.t.length > 0);
  // 去重（保险：同一句只留一条）
  const seen = new Set();
  FLAT = FLAT.filter(x => { const k = x.t; if (seen.has(k)) return false; seen.add(k); return true; });
  // 保证与 STEP 互质：若 N 恰为 97 的倍数，追加一条备用句
  if (FLAT.length % STEP === 0) {
    FLAT.push({ t: '把今天过好，就是了不起的事。', c: '生活' });
  }
})();

function dateStrOf(d) {
  const dt = d || new Date();
  const y = dt.getFullYear();
  const m = String(dt.getMonth() + 1).padStart(2, '0');
  const day = String(dt.getDate()).padStart(2, '0');
  return y + '-' + m + '-' + day;
}

// dateStr → 自纪元天数（UTC 意义，本地日期零点），跨时区稳定
function dayIndexOf(dateStr) {
  const s = dateStr || dateStrOf();
  const p = String(s).split('-').map(Number);
  const y = p[0] || 2026, m = (p[1] || 1) - 1, d = p[2] || 1;
  return Math.floor(Date.UTC(y, m, d) / 86400000);
}

// 取某天第 offset 条（offset=0 为当日主推；>0 用于「换一句」）
function quoteForDate(dateStr, offset) {
  const N = FLAT.length;
  const di = dayIndexOf(dateStr);
  const k = Math.max(0, Number(offset) || 0);
  const idx = ((di + k * STEP) % N + N) % N;
  const e = FLAT[idx];
  // text 为 t 的可读别名（页面层用 .text 更不易误写；库内遍历用 .t）
  return Object.assign({ index: idx, date: dateStr || dateStrOf(), offset: k, text: e.t }, e);
}

// 今天的主推（本地自然日）
function todayQuote(offset) {
  return quoteForDate(dateStrOf(), offset);
}

function poolSize() { return FLAT.length; }

// ── 海报文案库：展平 + 去重 + 确定性轮换（与通用金句库完全独立的另一套）──
const POSTER_FLAT = (function () {
  const a = (POSTER_POOL || []).map(s => String(s || '').trim()).filter(s => s.length > 0);
  const seen = new Set();
  return a.filter(s => { if (seen.has(s)) return false; seen.add(s); return true; });
})();

function posterQuote(offset) {
  const N = POSTER_FLAT.length;
  const di = dayIndexOf(dateStrOf());
  const k = Math.max(0, Number(offset) || 0);
  const idx = ((di + k * STEP) % N + N) % N;
  const text = POSTER_FLAT[idx];
  return { index: idx, date: dateStrOf(), offset: k, text: text, t: text };
}

function posterPoolSize() { return POSTER_FLAT.length; }

// ── 日签卡文案：按「时段」选早安 / 晚安 / 白天通用，再按日期轮换 ──
//   上午（<11 点）用 morning，傍晚后（>=18 点）用 night，白天用 growth+life 通用，
//   既贴合「日签」的早安晚安语义，又让早安/晚安扩充文案真正被用上。
function dailySignQuote(offset) {
  const h = new Date().getHours();
  const arr = (h < 11) ? POOL.morning : (h >= 18 ? POOL.night : POOL.growth.concat(POOL.life));
  const N = arr.length;
  const di = dayIndexOf(dateStrOf());
  const k = Math.max(0, Number(offset) || 0);
  const idx = ((di + k * STEP) % N + N) % N;
  const text = arr[idx];
  return { index: idx, text: text, t: text, part: h < 11 ? 'morning' : (h >= 18 ? 'night' : 'day') };
}

