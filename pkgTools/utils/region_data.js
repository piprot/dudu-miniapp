// 直辖市：picker 第二级展示的是「区」，但成卡文案里读起来更像地点，故保留原名。
const MUNICIPALITIES = ['北京', '天津', '上海', '重庆'];

const PROVINCE_NAMES = PROVINCES.map(p => p.name);

/** 取某省的市级列表；未知省名回退到第一省（避免空数组把 picker 搞坏）。 */
function citiesOf(provinceName) {
  const hit = PROVINCES.find(p => p.name === provinceName);
  return hit ? hit.cities.slice() : PROVINCES[0].cities.slice();
}

/** 判断某省是否为直辖市（成卡文案与 UI 措辞用）。 */
function isMunicipality(provinceName) {
  return MUNICIPALITIES.indexOf(provinceName) >= 0;
}

/** 地点短标签，用于成卡标题等窄空间：省级名与市级名都去掉后缀，「江苏省苏州市」→「江苏苏州」。 */
function shortName(provinceName, cityName) {
  const strip = s => String(s || '').replace(/(省|市|自治区|特别行政区)$/, '');
  if (!provinceName || !cityName) return strip(provinceName || cityName);
  return strip(provinceName) + strip(cityName);
}

/** 「江苏省苏州市」这类全名；直辖市拼成「上海市浦东新区」。缺省名则不拼（防裸市名）。 */
function fullName(provinceName, cityName) {
  if (!provinceName || !cityName) return provinceName || '';
  return provinceName + cityName;
}

/** 校验名称是否在库中（防止手改 storage 注入脏值）。 */
function isValid(provinceName, cityName) {
  const p = PROVINCES.find(x => x.name === provinceName);
  if (!p) return false;
  return !!cityName && p.cities.indexOf(cityName) >= 0;
}

/** 库里是否存在这个城市（用于测试与容错）。 */
function hasCity(cityName) {
  return PROVINCES.some(p => p.cities.indexOf(cityName) >= 0);
}

function stats() {
  const cityCount = PROVINCES.reduce((n, p) => n + p.cities.length, 0);
  return { provinces: PROVINCES.length, cities: cityCount, municipalities: MUNICIPALITIES.length };
}

module.exports = {
  PROVINCES,
  PROVINCE_NAMES,
  MUNICIPALITIES,
  citiesOf,
  isMunicipality,
  shortName,
  fullName,
  isValid,
  hasCity,
  stats
};