const CAT_NAME = { morning: '早安', night: '晚安', growth: '成长', life: '生活', craft: '创作', mood: '心绪' };

// 展平为 [{t, c}]，并保证总条数与步长 97 互质（不是 97 的倍数），否则补一条兜底句。
let FLAT = [];
(function build() {
  for (const g of Object.keys(POOL)) {
    for (const t of POOL[g]) FLAT.push({ t: String(t || '').trim(), c: CAT_NAME[g] || '' });
  }
  FLAT = FLAT.filter(x => x.t.length > 0);
  // 去重（保险：同一句只留一条）
  const seen = new Set();
  FLAT = FLAT.filter(x => { const k = x.t; if (seen.has(k)) return false; seen.add(k); return true; });
  // 保证与 STEP 互质：若 N 恰为 97 的倍数，追加一条备用句
  if (FLAT.length % STEP === 0) {
    FLAT.push({ t: '把今天过好，就是了不起的事。', c: '生活' });
  }
})();

function dateStrOf(d) {
  const dt = d || new Date();
  const y = dt.getFullYear();
  const m = String(dt.getMonth() + 1).padStart(2, '0');
  const day = String(dt.getDate()).padStart(2, '0');
  return y + '-' + m + '-' + day;
}

// dateStr → 自纪元天数（UTC 意义，本地日期零点），跨时区稳定
function dayIndexOf(dateStr) {
  const s = dateStr || dateStrOf();
  const p = String(s).split('-').map(Number);
  const y = p[0] || 2026, m = (p[1] || 1) - 1, d = p[2] || 1;
  return Math.floor(Date.UTC(y, m, d) / 86400000);
}

// 取某天第 offset 条（offset=0 为当日主推；>0 用于「换一句」）
function quoteForDate(dateStr, offset) {
  const N = FLAT.length;
  const di = dayIndexOf(dateStr);
  const k = Math.max(0, Number(offset) || 0);
  const idx = ((di + k * STEP) % N + N) % N;
  const e = FLAT[idx];
  // text 为 t 的可读别名（页面层用 .text 更不易误写；库内遍历用 .t）
  return Object.assign({ index: idx, date: dateStr || dateStrOf(), offset: k, text: e.t }, e);
}

// 今天的主推（本地自然日）
function todayQuote(offset) {
  return quoteForDate(dateStrOf(), offset);
}

function poolSize() { return FLAT.length; }

