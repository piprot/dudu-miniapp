const CATS = ['life', 'love', 'work', 'time', 'growth', 'calm'];
const KINDS = ['quote', 'line', 'book', 'famous', 'daily'];
const NEED = 30;   // 每个 (分类,来源) 组合新增 30 条 → 30 → 60
const NG = 4;      // 主题组数
const NA = 9;      // 每组情境数
const NB = 9;      // 每组落点数

// ─────────────────── 工具 ───────────────────
function bad(s) { // 词池自检：不得含英文/数字/句末标点/空
  return !s || typeof s !== 'string' || /[a-zA-Z0-9]/.test(s) || /[。！？；]$/.test(s);
}
function shareNgram(a, b, n) { // 共享 ≥n 字子串 → 同义反复，丢弃
  for (let i = 0; i + n <= a.length; i++) {
    if (b.indexOf(a.substr(i, n)) >= 0) return true;
  }
  return false;
}

const seen = new Set(); // 全局去重

function run() {
  const raw = [];
  // ⚠️ k 必须**跨组合全局递增**：若每个 (分类,来源) 都从 0 开始，
  //    相邻来源类型会取到同一组 (情境,落点)，只差句式 → 正是「切来源类型句子不变」的老毛病。
  let k = 0;
  CATS.forEach(cat => {
    const P = POOLS[cat];
    if (P.G.length !== NG) throw new Error(cat + ' 主题组数应为 ' + NG);
    P.G.forEach((g, gi) => {
      [].concat(g.A, g.B).forEach(s => {
        if (bad(s)) throw new Error('词池不合格 [' + cat + ' G' + gi + ']: ' + s);
      });
      if (g.A.length !== NA || g.B.length !== NB) throw new Error(cat + ' G' + gi + ' 词池数量不为 9');
    });
    P.C.forEach(s => { if (bad(s)) throw new Error('C 词池不合格 [' + cat + ']: ' + s); });

    KINDS.forEach((kind, ki) => {
      const T = KIND_TPL[kind], NT = T.length;
      const got = [];
      let guard = 0;
      while (got.length < NEED && guard++ < NG * NA * NB * NT * 6) {
        // 四者同时变化：gi 主题组 / ai 情境 / bi 落点 / ti 句式
        // 周期 lcm(4,9,9,7)=252 > 150（每分类 5 来源 ×30），保证不重复
        const gi = k % NG;
        const ai = (k * 1) % NA;
        const bi = (k * 7 + 3) % NB;
        const ti = (k * 5 + 1) % NT;
        k++;
        const G = P.G[gi];
        const a = G.A[ai], b = G.B[bi];
        const c = P.C[(gi * 3 + ai) % P.C.length];
        const tpl = T[ti];
        if (!tpl.ok(a, b, c)) continue;
        // 共享 ≥3 字子串即丢弃：4 字门槛漏掉了「今天你想起一件小事笑了，小事里藏着好心情」这类回环
        if (shareNgram(a, b, 3)) continue;
        const text = tpl.fn(a, b, c);
        if (text.length > 58) continue;
        if (seen.has(text)) continue;
        seen.add(text);
        const catWord = P.C[(gi * 3 + ai) % P.C.length];
        let tagWord = P.T[(gi * 3 + bi) % P.T.length];
        if (tagWord === catWord) tagWord = P.T[(gi * 3 + bi + 1) % P.T.length];
        got.push({ text: text, tags: catWord + ',' + tagWord });
      }
      if (got.length < NEED) throw new Error(cat + '/' + kind + ' 只产出 ' + got.length + ' 条');
      got.forEach((g, i) => {
        raw.push({
          id: 'q_seed_' + cat + '_' + kind + '_' + String(31 + i).padStart(2, '0'),
          text: g.text,
          tags: g.tags
        });
      });
    });
  });
  return raw;
}

