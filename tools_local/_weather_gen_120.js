// ── 句式模板：都是口语里真会用的承接，避免「于是/因此」这类书面连接词
//    （书面连接词会让整条文案像作文，不像人说话）。
//
// ⚠️ 每个模板带一个 ok(A) 前置校验（2026-10-25 踩坑补的）：
//    光有替换规则不够，意象本身有形态差异，硬套会出语法硬伤——
//      · 「晒到的那块皮肤是暖的」+「的时候」→ 「…是暖的的时候」，叠字，一眼假。
//      · 「天光是平的，不分早晚」再套「看着…，」/「…，这会儿…」→ 三截句，读着断气。
//    所以：结尾带「的」的意象不进「的时候」；自带逗号的意象不进「看着」和「这会儿」。
// ok(a, b)：a=意象片段，b=心情落点片段。返回 false 则该模板跳过。
const TEMPLATES = [
  // 逗号直连：意象和落点都自带逗号时会变成三截句（读着断气），只允许一边有逗号
  { fn: (a, b) => a + '，' + b + '。', ok: (a, b) => !(a.indexOf('，') >= 0 && b.indexOf('，') >= 0) },
  { fn: (a, b) => a + '。' + b + '。', ok: () => true },
  // 「的时候」：意象以「的」结尾会叠成「…的的时候」；自带逗号则句式太散
  { fn: (a, b) => a + '的时候，' + b + '。', ok: (a) => !/的$/.test(a) && a.indexOf('，') < 0 },
  { fn: (a, b) => a + '——' + b + '。', ok: () => true },
  { fn: (a, b) => '看着' + a + '，' + b + '。', ok: (a) => a.indexOf('，') < 0 },
  { fn: (a, b) => a + '；' + b + '。', ok: () => true },
  { fn: (a, b) => a + '，这会儿' + b + '。', ok: (a) => a.indexOf('，') < 0 }
];

// 全局查重：既有 1536 条 + 本次已生成的，都不能撞
const used = new Set();
Object.keys(cur.MATRIX).forEach(k => cur.MATRIX[k].forEach(s => used.add(s)));

const ADD = {};
let made = 0;

WEATHER.forEach(w => {
  MOODS.forEach(m => {
    const key = w + '|' + m;
    const have = (cur.MATRIX[key] || []).length;
    const need = Math.max(0, PER_COMBO - have);
    if (!need) { ADD[key] = []; return; }

    const imgs = IMG[w], tails = TAIL[m];
    const out = [];

    // ⚠️ 遍历顺序是质量的生死线（2026-10-25 踩坑并修正）：
    //   最早写成「外层落点 → 中层意象 → 内层句式」，结果是同一对 (意象,落点)
    //   连着产出 7 条、**只差标点**——抽检一看就是「阳光斜斜铺了一地，你的笑也别省着。」
    //   「阳光斜斜铺了一地。你的笑也别省着。」「阳光斜斜铺了一地的时候，…」
    //   这种机器味是用户一眼能看穿的，比文案少更伤。
    //
    //   改为**对角线扫**：每一轮 d 里，ai 从 0 走到 7 且 bi = (ai+d)%8，
    //   于是同一轮内 8 条两两不同（ai 全不重复、bi 也全不重复）；
    //   轮与轮之间 bi 整体错位，跨轮也不撞。句式再按序号取模轮换。
    //   最终相邻两条的「意象 / 落点 / 句式」三者同时变化。
    const NI = imgs.length, NT = tails.length;
    const rounds = Math.max(NI, NT);
    for (let d = 0; d < rounds && out.length < need; d++) {
      for (let i = 0; i < NI && out.length < need; i++) {
        const ai = i;
        const bi = (i + d) % NT;
        const A = imgs[ai], B = tails[bi];
        // 从该用的那个模板开始往后找第一个「语法上套得住」的，避免叠字/三截句
        let t = null;
        for (let k = 0; k < TEMPLATES.length; k++) {
          const cand = TEMPLATES[((d + i) % TEMPLATES.length + k) % TEMPLATES.length];
          if (cand.ok(A, B)) { t = cand; break; }
        }
        if (!t) continue;
        const s = t.fn(A, B);
        if (used.has(s)) continue;
        used.add(s);
        out.push(s);
      }
    }
    // 兜底：若因撞车没凑够，再放宽句式轮换补一轮（仍保证全局唯一）
    for (let d = 0; d < rounds && out.length < need; d++) {
      for (let i = 0; i < NI && out.length < need; i++) {
        for (let ti = 0; ti < TEMPLATES.length && out.length < need; ti++) {
          const A = imgs[i], B = tails[(i + d) % NT];
          const tpl = TEMPLATES[(ti + i + d) % TEMPLATES.length];
          if (!tpl.ok(A, B)) continue;
          const s = tpl.fn(A, B);
          if (used.has(s)) continue;
          used.add(s);
          out.push(s);
        }
      }
    }
    if (out.length < need) {
      throw new Error(key + ' 只生成 ' + out.length + ' 条（需 ' + need + ' 条），池不够或撞车过多');
    }
    ADD[key] = out;
    made += out.length;
  });
});

module.exports = { ADD, made, WEATHER, MOODS, PER_COMBO };

